#!/usr/bin/env python3
"""Build the .app_reloc table for a self-relocating ATOS .APP (port/crt0.S).

usage: mkreloc.py LINKED.elf OUT.S            write the table as assembler
       mkreloc.py --check LINKED.elf TABLE.S  verify a final link against it

LINKED.elf must be linked at 0 with -Wl,--emit-relocs (-q).  Every R_68K_32
relocation whose target word lies inside the loaded image (header excluded) and
whose symbol is defined in a real section is an absolute address that crt0
must rebase.  Absolute 16/8-bit relocations against section symbols cannot be
rebased and are rejected.  Dependency-free (no pyelftools)."""
import struct
import sys

R_68K_32, R_68K_16, R_68K_8 = 1, 2, 3
R_68K_PC32, R_68K_PC16, R_68K_PC8 = 4, 5, 6
SHT_SYMTAB, SHT_RELA, SHT_REL, SHT_NOBITS = 2, 4, 9, 8
SHN_UNDEF, SHN_ABS = 0, 0xFFF1
SHF_ALLOC = 2


def die(msg):
    raise SystemExit("mkreloc: " + msg)


def read_elf(path):
    data = open(path, "rb").read()
    if data[:4] != b"\x7fELF" or data[4] != 1 or data[5] != 2:
        die(f"{path}: not a 32-bit big-endian ELF")
    (e_type, e_machine, _v, _entry, _phoff, shoff, _flags, _ehsize, _phes, _phn,
     shentsize, shnum, shstrndx) = struct.unpack_from(">HHIIIIIHHHHHH", data, 16)
    if e_machine != 4:
        die(f"{path}: not an m68k ELF (machine {e_machine})")
    sections = []
    for i in range(shnum):
        f = struct.unpack_from(">IIIIIIIIII", data, shoff + i * shentsize)
        sections.append(dict(name_off=f[0], type=f[1], flags=f[2], addr=f[3], offset=f[4],
                             size=f[5], link=f[6], info=f[7], entsize=f[9]))
    names = sections[shstrndx]
    for s in sections:
        o = names["offset"] + s["name_off"]
        s["name"] = data[o:data.index(b"\0", o)].decode()
    return data, sections


def relocations(path):
    data, sections = read_elf(path)
    by_name = {s["name"]: s for s in sections}
    header = by_name.get(".app_header")
    if not header:
        die("no .app_header section")
    loaded = [s for s in sections if s["flags"] & SHF_ALLOC and s["type"] != SHT_NOBITS]
    image_end = max(s["addr"] + s["size"] for s in loaded)
    out = set()
    for rs in sections:
        if rs["type"] not in (SHT_RELA, SHT_REL):
            continue
        target = sections[rs["info"]]
        if not target["flags"] & SHF_ALLOC or target["type"] == SHT_NOBITS:
            continue
        symtab = sections[rs["link"]]
        entsize = 12 if rs["type"] == SHT_RELA else 8
        for k in range(rs["size"] // entsize):
            r_offset, r_info = struct.unpack_from(">II", data, rs["offset"] + k * entsize)
            rtype, rsym = r_info & 0xFF, r_info >> 8
            if rtype in (R_68K_PC32, R_68K_PC16, R_68K_PC8, 0):
                continue
            sym = struct.unpack_from(">IIIBBH", data, symtab["offset"] + rsym * 16)
            shndx = sym[5]
            if shndx in (SHN_UNDEF, SHN_ABS):
                continue          # weak-undefined or absolute value: not an address
            if header["addr"] <= r_offset < header["addr"] + header["size"]:
                continue          # header fields are image OFFSETS, never rebased
            if not (0 <= r_offset < image_end):
                continue
            if rtype == R_68K_32:
                if r_offset & 1:
                    die(f"odd relocation offset 0x{r_offset:x} in {target['name']}")
                out.add(r_offset)
            elif rtype in (R_68K_16, R_68K_8):
                die(f"absolute {16 if rtype == R_68K_16 else 8}-bit relocation at "
                    f"0x{r_offset:x} in {target['name']} cannot be rebased")
            else:
                die(f"unsupported relocation type {rtype} at 0x{r_offset:x} in {target['name']}")
    reloc_sec = by_name.get(".app_reloc")
    if reloc_sec:
        lo, hi = reloc_sec["addr"], reloc_sec["addr"] + reloc_sec["size"]
        out = {o for o in out if not lo <= o < hi}
    return sorted(out)


def write_table(offsets, path):
    with open(path, "w") as f:
        f.write("/* generated by tools/mkreloc.py - do not edit */\n")
        f.write('    .section .app_reloc,"a"\n')
        f.write(f"    .long {len(offsets)}\n")
        for i in range(0, len(offsets), 8):
            f.write("    .long " + ",".join(f"0x{o:x}" for o in offsets[i:i + 8]) + "\n")


def read_table(path):
    vals = []
    for line in open(path):
        line = line.strip()
        if line.startswith(".long"):
            vals += [int(v, 0) for v in line[5:].split(",")]
    return vals[1:]


def main(argv):
    if len(argv) == 4 and argv[1] == "--check":
        final, table = relocations(argv[2]), read_table(argv[3])
        if final != table:
            die(f"relocation table is stale: {len(table)} in table, {len(final)} in {argv[2]}")
        print(f"mkreloc: {len(final)} relocations verified")
        return
    if len(argv) != 3:
        die(__doc__)
    offs = relocations(argv[1])
    write_table(offs, argv[2])
    print(f"mkreloc: {len(offs)} relocations -> {argv[2]}")


if __name__ == "__main__":
    main(sys.argv)
