#!/usr/bin/env python3
"""Generate editable ASCII .LNG packs and the generated catalog header.

Besides the key/English switches the header carries the byte offset of every
value in each generated pack, so a native app adopts a pack with a table copy
instead of re-parsing key names at startup. The offsets are valid only for the
exact generated file; a length+header check selects the table and a
hand-edited pack falls back to the in-app parser.
"""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
rows=json.loads((root/'languages/catalog.json').read_text())
assert len({r['key'] for r in rows})==len(rows)
offsets={}
lengths={}
for lang in ['en','pl']:
    lines=['ATOS-LNG-1','# ASCII; key=value; escapes: \\n and \\\\; spaces are significant.']
    for r in rows:
        value=r[lang]
        assert value and len(value)<=78 and value.isascii(),r['key']
        lines.append(r['key']+'='+value.replace('\\','\\\\').replace('\n','\\n'))
    text='\n'.join(lines)+'\n'
    (root/'languages'/f'{lang.upper()}.LNG').write_text(text,encoding='ascii')
    pos=0
    table={}
    for line in lines:
        if line!='ATOS-LNG-1' and not line.startswith('#'):
            eq=line.find('=')
            if eq>0: table[line[:eq]]=pos+eq+2
        pos+=len(line)+1
    offsets[lang]=table
    lengths[lang]=len(text)
header=['/* Generated by tools/make_languages.py. Stable keys: languages/catalog.json. */']
for group in ['CMD','SYS','SET']:
    rr=[r for r in rows if r['key'].startswith(group+'_')]
    header+=['#ifdef LNG_'+group,
             'enum { '+', '.join(r['key'] for r in rr)+', LNG_COUNT };',
             'static const unsigned short lng_off_en[LNG_COUNT]={'+','.join(str(offsets['en'][r['key']]) for r in rr)+'};',
             'static const unsigned short lng_off_pl[LNG_COUNT]={'+','.join(str(offsets['pl'][r['key']]) for r in rr)+'};',
             'static const unsigned short lng_len_en='+str(lengths['en'])+',lng_len_pl='+str(lengths['pl'])+';',
             'static const char *lng_key(unsigned id) { switch(id) {']
    header+=['case '+r['key']+': return '+json.dumps(r['key'])+';' for r in rr]
    header+=['default: return ""; }}','static const char *lng_english(unsigned id) { switch(id) {']
    header+=['case '+r['key']+': return '+json.dumps(r['en'])+';' for r in rr]
    header+=['default: return ""; }}','#endif']
(root/'include/lng_catalog.h').write_text('\n'.join(header)+'\n')
