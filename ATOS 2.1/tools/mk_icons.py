#!/usr/bin/env python3
"""Convert PNG icons (free Linux icon sets) to 1-bpp C arrays for ATOS DESKTOP.
Usage: mk_icons.py out.h ICON_NAME=file.png [NAME2=file2.png ...]
Needs Pillow:  python3 -m pip install pillow
"""
import sys, pathlib

try:
    from PIL import Image
except ImportError:
    print("Pillow missing: python3 -m pip install pillow", file=sys.stderr)
    sys.exit(1)


def to_bits(path, size=32, threshold=128, invert=True):
    img = Image.open(path).convert("RGBA")
    img = img.resize((size, size))
    rows = []
    for y in range(size):
        row = 0
        for x in range(size):
            r, g, b, a = img.getpixel((x, y))
            lum = (r * 299 + g * 587 + b * 114) // 1000
            on = a > 40 and lum < threshold
            if not invert:
                on = not on
            row = (row << 1) | (1 if on else 0)
        rows.append(row)
    return rows


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    out = pathlib.Path(sys.argv[1])
    lines = ["/* generated by mk_icons.py - 32x32 1bpp icons */"]
    for spec in sys.argv[2:]:
        name, _, path = spec.partition("=")
        rows = to_bits(path)
        lines.append("static const unsigned long ic_%s[32] = {" % name)
        for r in rows:
            lines.append("    0x%08XUL," % r)
        lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
