from pathlib import Path
# Analytical voltage-divider model, not a copied emulator volume table.
# For two equal channels, normalized voltage follows the 3 dB volume steps.
# Solve V = 2*g / (1 + 2*g) for per-channel conductance g, then sum
# conductances of three channels into the ST's common output load.
# Chip/loading tolerances mean this remains an approximation on real hardware.
levels=[0.0]
for i in range(1,16):
 v=0.5*2**((i-15)/2)
 levels.append(v/(2*(1-v)))
combinations=[]
for a in range(16):
 for b in range(16):
  for c in range(16):
   g=levels[a]+levels[b]+levels[c]
   combinations.append((g/(1+g),a,b,c))
lut=[]
for i in range(256):
 target=i*0.6/255
 _,a,b,c=min(combinations,key=lambda v:abs(v[0]-target))
 lut.append((a<<16)|(b<<8)|c)
(Path(__file__).resolve().parent.parent/'system/pcm_lut.h').write_text('/* Generated by tools/gen_pcm_lut.py: YM voltage-divider model, 3 channels.\n * 0x00AABBCC volume registers. Approximate; real analogue output may vary. */\nconst uint32_t kpcm_lut[256]={\n'+''.join('0x%06xu,%s'%(x,'\n' if i%8==7 else '') for i,x in enumerate(lut))+'};\n')
